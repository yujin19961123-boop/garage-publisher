import {env,api,login,request,zip} from './test-helpers.mjs';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const session=await login(env.INIT_ADMIN_USERNAME,env.INIT_ADMIN_PASSWORD);
const tail=Date.now().toString(36);
const name='客服系统'+tail;
const first=await api('/projects','POST',{name},session);
const second=await api('/projects','POST',{name},session);
const third=await api('/projects','POST',{name},session);
assert.equal(first.publicId,'kefuxitong'+tail);
assert.equal(second.publicId,first.publicId+'111');
assert.equal(third.publicId,first.publicId+'222');
const renamed=await api('/projects/'+first.id,'PATCH',{name:'已改名'},session);
assert.equal(renamed.url,first.url);
const d=await api('/projects/'+first.id+'/deployments','POST',{},session);
await api('/deployments/'+d.id+'/archive','PUT',zip({'index.html':'pinyin-preview'}),session,202);
let done=false;for(let i=0;i<80;i++){const r=await api('/deployments/'+d.id,'GET',undefined,session);if(r.status==='SUCCEEDED'){done=true;break;}if(r.status==='FAILED')throw Error(r.errorMessage);await new Promise(r=>setTimeout(r,250));}assert.ok(done);
assert.equal(new URL(first.url).hostname,'localhost');
assert.equal(new URL(first.url).pathname,'/'+first.publicId+'/');
assert.equal((await request(new URL(first.url).pathname,{host:new URL(first.url).host})).text,'pinyin-preview');
const old=JSON.parse(readFileSync('.local/dist-result.json','utf8'));
assert.equal((await request('/',{host:new URL(old.url).host})).status,200);
const again=await api('/projects/'+old.projectId,'GET',undefined,session);
assert.equal(again.url,old.url);
const concurrent=await Promise.all(Array.from({length:3},()=>api('/projects','POST',{name:'并发项目'+tail},session)));
assert.equal(new Set(concurrent.map(x=>x.publicId)).size,3);
console.log('PASS: pinyin name, preferred suffix 111/222, immutable URL after rename, concurrent uniqueness, new path preview published, legacy URL preserved.');
