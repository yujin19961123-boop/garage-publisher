import {env,request,api,login,publish,zip} from './test-helpers.mjs';
import assert from 'node:assert/strict';
const admin=await login(env.INIT_ADMIN_USERNAME,env.INIT_ADMIN_PASSWORD);
const suffix=Date.now().toString(36),password='123456';
const member=await api('/admin/users','POST',{username:'member_'+suffix,password},admin);
