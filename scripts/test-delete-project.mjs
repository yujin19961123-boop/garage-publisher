import {env,api,login,publish,request,zip} from './test-helpers.mjs';
import {writeFileSync,existsSync} from 'node:fs';
import assert from 'node:assert/strict';
const admin=await login(env.INIT_ADMIN_USERNAME,env.INIT_ADMIN_PASSWORD);
const suffix=Date.now().toString(36),password='123456';
const member=await api('/admin/users','POST',{username:'delete_test_'+suffix,password},admin);
writeFileSync('.local/delete-test-account.json',JSON.stringify({id:member.id,username:member.username}));
const session=await login(member.username,password);
const name='Delete test '+suffix;
const project=await api('/projects','POST',{name},admin);
const other=await api('/projects','POST',{name:'Member delete test '+suffix},session);
await api('/projects/'+project.id,'DELETE',undefined,session,403);
await api('/projects/'+other.id,'DELETE',undefined,admin,403);
const denied=await request('/api/v1/projects/'+project.id,{method:'DELETE',session:{cookie:admin.cookie,csrf:''}});
assert.equal(denied.status,403);
await api('/projects/'+other.id,'DELETE',undefined,session);
assert.ok(!(await api('/projects','GET',undefined,session)).items.some(p=>p.id===other.id));
await publish(project,{'index.html':'delete-test-page','assets/app.js':'const x=1;'},admin);
const share=await api('/share-page','POST',{},admin),shareURL=new URL(share.url),projectURL=new URL(project.url);
assert.ok((await request(shareURL.pathname,{host:shareURL.host})).text.includes(name));
assert.equal((await request(projectURL.pathname,{host:projectURL.host})).status,200);
await api('/projects/'+project.id,'DELETE',undefined,admin);
await api('/projects/'+project.id,'GET',undefined,admin,404);
await api('/projects/'+project.id,'DELETE',undefined,admin,404);
assert.equal((await request(projectURL.pathname,{host:projectURL.host})).status,404);
assert.ok(!(await request(shareURL.pathname,{host:shareURL.host})).text.includes(name));
for(let i=0;i<30&&existsSync('.local/data/releases/'+project.id);i++)await new Promise(r=>setTimeout(r,200));
assert.ok(!existsSync('.local/data/releases/'+project.id),'release files should be cleaned');
const again=await api('/projects','POST',{name},admin);
assert.notEqual(again.url,project.url,'deleted public URL must never point at a new project');
const pending=await api('/projects/'+again.id+'/deployments','POST',{},admin);
await api('/projects/'+again.id,'DELETE',undefined,admin,409);
await api('/deployments/'+pending.id+'/archive','PUT',zip({'index.html':'busy-test'}),admin,202);
let completed=false;
for(let i=0;i<80;i++){const d=await api('/deployments/'+pending.id,'GET',undefined,admin);if(d.status==='SUCCEEDED'){completed=true;break;}if(d.status==='FAILED')throw Error(d.errorMessage);await new Promise(r=>setTimeout(r,250));}
assert.ok(completed);
await api('/projects/'+again.id,'DELETE',undefined,admin);
assert.equal((await request(projectURL.pathname,{host:projectURL.host})).status,404);
console.log('PASS: owner-only deletion, admin boundary, CSRF, unpublished/published deletion, vanished link/list/collection, file cleanup, tombstoned URL, busy deployment rejection.');
