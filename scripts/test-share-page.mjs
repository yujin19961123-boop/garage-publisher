import {env,api,login,publish,request} from './test-helpers.mjs';
import assert from 'node:assert/strict';
const admin=await login(env.INIT_ADMIN_USERNAME,env.INIT_ADMIN_PASSWORD);
const suffix=Date.now().toString(36),password='123456';
const userA=await api('/admin/users','POST',{username:'share_a_'+suffix,password},admin);
const userB=await api('/admin/users','POST',{username:'share_b_'+suffix,password},admin);
const a=await login(userA.username,password),b=await login(userB.username,password);
const page=await api('/share-page','POST',{},a);
const pageURL=new URL(page.url);
const readPage=(method='GET')=>request(pageURL.pathname,{method,host:pageURL.host});
assert.equal(page.publishedCount,0);
assert.equal((await readPage()).status,200);
const repeats=await Promise.all(Array.from({length:3},()=>api('/share-page','POST',{},a)));
assert.ok(repeats.every(x=>x.url===page.url));
const draftName='Hidden draft '+suffix;
await api('/projects','POST',{name:draftName},a);
const first=await api('/projects','POST',{name:'Shared first '+suffix},a);
await publish(first,{'index.html':'first'},a);
const foreign=await api('/projects','POST',{name:'Other member '+suffix},b);
await publish(foreign,{'index.html':'foreign'},b);
let html=(await readPage()).text;
assert.ok(html.includes(first.name));
assert.ok(!html.includes(draftName));
assert.ok(!html.includes(foreign.name));
assert.ok(html.includes(new URL(first.url).pathname));
assert.ok(!html.includes(userA.id));
assert.ok(!html.includes(userA.username));
assert.ok(!html.includes(first.id));
const adminPage=await api('/share-page','POST',{},admin);
const adminURL=new URL(adminPage.url);
const adminHTML=(await request(adminURL.pathname,{host:adminURL.host})).text;
assert.ok(!adminHTML.includes(first.name));
assert.ok(!adminHTML.includes(foreign.name));
assert.equal((await request('/api/v1/share-page',{method:'POST',body:{}})).status,401);
assert.equal((await api('/share-page','POST',{},a)).publishedCount,1);
const renamed='Updated name '+suffix;
await api('/projects/'+first.id,'PATCH',{name:renamed},a);
html=(await readPage()).text;assert.ok(html.includes(renamed));assert.ok(!html.includes(first.name));
await publish(first,{'missing.html':'invalid'},a,'spa','FAILED');
assert.ok((await readPage()).text.includes(renamed));
const malicious='<img src=x onerror=alert(1)>';
const second=await api('/projects','POST',{name:malicious},a);
await publish(second,{'index.html':'second'},a);
html=(await readPage()).text;
assert.ok(!html.includes('<img src=x'));
assert.ok(html.includes('&lt;img'));
assert.equal((await api('/share-page','POST',{},a)).publishedCount,2);
assert.equal((await readPage()).headers['cache-control'],'no-store');
assert.equal((await readPage('HEAD')).text,'');
assert.equal((await request('/_share/not-found-unique-'+suffix+'/',{host:pageURL.host})).status,404);
assert.equal((await request(pageURL.pathname,{method:'POST',host:pageURL.host})).status,405);
const otherPage=await api('/share-page','POST',{},b);
assert.notEqual(otherPage.url,page.url);
await api('/admin/users/'+userA.id+'/status','PATCH',{status:'disabled'},admin);
assert.equal((await readPage()).status,200);
assert.ok((await readPage()).text.includes(renamed));
console.log('PASS: own published projects only, anonymous page, stable/concurrent sharing, live changes, hidden drafts/other users, escaped content, failed update preservation, HEAD/404/405, disabled owner keeps published content.');
console.log(page.url);
